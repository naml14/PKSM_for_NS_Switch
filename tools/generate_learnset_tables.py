#!/usr/bin/env python3
"""Generate FRLG learnsets from the public pret/pokefirered source."""
import re
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RAW = "https://raw.githubusercontent.com/pret/pokefirered/master/"
FILES = {
    "level": "src/data/pokemon/level_up_learnsets.h",
    "pointers": "src/data/pokemon/level_up_learnset_pointers.h",
    "machines": "src/data/pokemon/tmhm_learnsets.h",
    "eggs": "src/data/pokemon/egg_moves.h",
    "species": "include/constants/species.h",
    "moves": "include/constants/moves.h",
}


def fetch(path):
    with urllib.request.urlopen(RAW + path) as response:
        return response.read().decode("utf-8")


def constants(text, prefix):
    return {name: int(value) for name, value in re.findall(
        r"^#define\s+(" + prefix + r"\w+)\s+(\d+)\s*$", text, re.M)}


def main():
    source = {name: fetch(path) for name, path in FILES.items()}
    species = constants(source["species"], "SPECIES_")
    moves = constants(source["moves"], "MOVE_")
    assert "#define LEVEL_UP_MOVE(lvl, move) ((lvl << 9) | move)" in source["level"]
    count = max(species.values()) + 1
    level_lists = {}
    for name, body in re.findall(r"static const u16\s+(\w+)\[\]\s*=\s*\{(.*?)\};", source["level"], re.S):
        entries = re.findall(r"LEVEL_UP_MOVE\(\s*(\d+)\s*,\s*(MOVE_\w+)\s*\)", body)
        assert "LEVEL_UP_END" in body and entries, name
        level_lists[name] = [(int(level), moves[move], move) for level, move in entries]
    levels = [[] for _ in range(count)]
    for name, table in re.findall(r"\[(SPECIES_\w+)\]\s*=\s*(\w+)", source["pointers"]):
        if name != "SPECIES_NONE":
            levels[species[name]] = level_lists[table]
    machines = [0] * count
    for name, body in re.findall(r"\[(SPECIES_\w+)\]\s*=\s*TMHM_LEARNSET\((.*?)\),", source["machines"], re.S):
        for kind, number in re.findall(r"TMHM\((TM|HM)(\d\d)_\w+\)", body):
            number = int(number) + (50 if kind == "HM" else 0)
            assert 1 <= number <= 58
            machines[species[name]] |= 1 << (number - 1)
    eggs = [[] for _ in range(count)]
    for name, body in re.findall(r"egg_moves\(\s*(\w+)\s*,(.*?)\)", source["eggs"], re.S):
        if "SPECIES_" + name not in species:
            # Skip the macro definition, not an entry.
            assert name == "species", name
            continue
        eggs[species["SPECIES_" + name]] = [(moves[move], move) for move in re.findall(r"MOVE_\w+", body)]
    assert levels[1] and machines[1] and eggs[1]
    header = '''// Generated by tools/generate_learnset_tables.py, the source of truth. Do not edit.
#pragma once
#include <cstddef>
#include <cstdint>
namespace pksm {
struct LevelUpMove {
    std::uint8_t level = 0;
    std::uint16_t move = 0;
};
std::size_t frlg_level_up_move_count(std::uint16_t species) noexcept;
const LevelUpMove& frlg_level_up_move(std::uint16_t species, std::size_t index) noexcept;
// Machines 1-50 are TM01-TM50; 51-58 are HM01-HM08.
bool frlg_learns_tmhm(std::uint16_t species, std::uint8_t machine) noexcept;
std::size_t frlg_egg_move_count(std::uint16_t species) noexcept;
std::uint16_t frlg_egg_move(std::uint16_t species, std::size_t index) noexcept;
}  // namespace pksm
'''
    out = ["// Generated by tools/generate_learnset_tables.py, the source of truth. Do not edit.", "// Sources:"]
    out += ["//   " + RAW + path for path in FILES.values()]
    out += ["// Machines 1-50 are TM01-TM50; 51-58 are HM01-HM08.",
            '#include "pksm/frlg_learnsets.hpp"', "namespace pksm {", "namespace {",
            "struct Range { std::size_t offset; std::size_t count; };", "constexpr LevelUpMove levels[] = {"]
    ranges = []
    offset = 0
    for entries in levels:
        ranges.append((offset, len(entries)))
        for level, move, name in entries:
            out.append(f"    {{{level}, {move}}}, // {name}")
        offset += len(entries)
    out += ["};", "constexpr Range level_ranges[] = {"]
    out += [f"    {{{offset}, {length}}}," for offset, length in ranges]
    out += ["};", "constexpr std::uint64_t machines[] = {"]
    out += [f"    UINT64_C({value})," for value in machines]
    out += ["};", "constexpr std::uint16_t eggs[] = {"]
    ranges = []
    offset = 0
    for entries in eggs:
        ranges.append((offset, len(entries)))
        for move, name in entries:
            out.append(f"    {move}, // {name}")
        offset += len(entries)
    out += ["};", "constexpr Range egg_ranges[] = {"]
    out += [f"    {{{offset}, {length}}}," for offset, length in ranges]
    out += ["};", f"constexpr std::size_t species_count = {count};", "constexpr LevelUpMove empty_move{};", "}  // namespace", '''
std::size_t frlg_level_up_move_count(std::uint16_t species) noexcept {
    return species < species_count ? level_ranges[species].count : 0;
}
const LevelUpMove& frlg_level_up_move(std::uint16_t species, std::size_t index) noexcept {
    if (index >= frlg_level_up_move_count(species)) return empty_move;
    return levels[level_ranges[species].offset + index];
}
bool frlg_learns_tmhm(std::uint16_t species, std::uint8_t machine) noexcept {
    return species < species_count && machine >= 1 && machine <= 58 &&
           (machines[species] & (UINT64_C(1) << (machine - 1))) != 0;
}
std::size_t frlg_egg_move_count(std::uint16_t species) noexcept {
    return species < species_count ? egg_ranges[species].count : 0;
}
std::uint16_t frlg_egg_move(std::uint16_t species, std::size_t index) noexcept {
    if (index >= frlg_egg_move_count(species)) return 0;
    return eggs[egg_ranges[species].offset + index];
}
}  // namespace pksm
''']
    (ROOT / "include/pksm/frlg_learnsets.hpp").write_text(header, encoding="utf-8", newline="\n")
    (ROOT / "src/frlg_learnsets.cpp").write_text("\n".join(out), encoding="utf-8", newline="\n")


if __name__ == "__main__":
    main()
